/**
 * عنوان IP العميل الموثوق لحدود المعدّل ودلاء الإساءة — مصدر واحد
 * لكل أسطح الخلفية (api.ts + sheerid/mod.ts). بيقفل W3 #4 وW6 #8
 * (نص XFF) من مراجعة الموقع.
 *
 * بوابة الدخول الحقيقية للمتجر: الزيارات بتوصل Deno Deploy عبر
 * وكيل Cloudflare (migoai.shop)، وCloudflare بيكتب
 * `cf-connecting-ip` بنفسه من TCP peer — قيمة واحدة بيحطها مدخل
 * إحنا متحكمين فيه، مش العميل. أما أول قفزة في `x-forwarded-for`
 * فالعميل يقدر يكتبها بنفسه ويدوّرها كل طلب (وهو ده أصل الضعف:
 * حدود 60/دقيقة و20/دقيقة كانت مربوطة بقيمة مزوّرة)، فمش بتتقرأ
 * هنا خالص — لا كأساسي ولا كاحتياطي.
 *
 * غياب الهيدر (طلب ما عدّاش على Cloudflare: نداء مباشر لأصل Deno
 * زي حلقاتنا إحنا أو نداءات المورد) = "unknown": دلو واحد مشترك.
 * ده الاتجاه الآمن المقصود — الحدود بتلزم أشد على القناة دي،
 * مش بتختفي، ومفيش قيمة من العميل بتتحول لمفتاح دلو أبدًا.
 */
export function clientIp(req: Request): string {
  const ip = (req.headers.get("cf-connecting-ip") || "").trim();
  return ip || "unknown";
}
