export function adminCompletedText(
  orderRef: string,
  job: { job_id: string; charged_usd: number },
): string {
  return (
    "✅ تحقق SheerID آلي (موقع) اكتمل واتسلّم\n" +
    `الطلب: ${orderRef}\n` +
    `معرّف العملية عند المورد: ${job.job_id}\n` +
    `اتخصم من محفظة المورد: ${job.charged_usd || 0} USD`
  );
}

export function adminFailedText(
  orderRef: string,
  job: { job_id: string; status: string },
  refundConfirmed: boolean,
): string {
  return (
    "⚠️ تحقق SheerID آلي (موقع) ماكتملش\n" +
    `الطلب: ${orderRef}\n` +
    `معرّف العملية عند المورد: ${job.job_id}\n` +
    `حالة العملية عندنا: ${job.status}\n` +
    (refundConfirmed
      ? "الاسترداد اتأكد في القاعدة (refund_order)."
      : "⚠️ الاسترداد لسه مش مؤكد في القاعدة — راجع الطلب يدويًا.")
  );
}

export function adminFallbackText(orderRef: string, reason: string): string {
  return (
    "⚠️ التحقق الآلي (موقع) مش متاح للطلب ده — كمّله يدويًا\n" +
    `السبب: ${reason || "غير معروف"}\n` +
    `الطلب: ${orderRef}`
  );
}

