/** إقرار استلام الرابط وبدء التحقق. */
export function startedText(): string {
  return (
    "وصلنا الرابط ✅\n" +
    "بدأنا التحقق حالًا، والنتيجة هتظهر هنا في نفس الصفحة.\n" +
    "سيب صفحة التحقق مفتوحة لحد ما النتيجة تظهر."
  );
}

/** التحقق طول عن نافذة الانتظار القصيرة: لسه شغّال وهنسلّم أول ما يخلص. */
export function stillProcessingText(): string {
  return (
    "التحقق لسه شغّال ⏳\n" +
    "هنظهر لك رابط التفعيل هنا أول ما يخلص — مش محتاج تعمل حاجة تانية."
  );
}

/** نتيجة النجاح: رابط التفعيل + تعليمة الاستلام. */
export function completedText(activationUrl: string): string {
  const lines = [
    "التحقق نجح ✅",
    "",
    "رابط تفعيل Google One AI Premium لمدة سنة:",
  ];
  if (activationUrl) lines.push(activationUrl);
  lines.push("");
  lines.push("افتح الرابط وانت متصل من أمريكا (VPN أمريكي) عشان تستلم خطتك.");
  return lines.join("\n");
}

